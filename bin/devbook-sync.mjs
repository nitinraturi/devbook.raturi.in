#!/usr/bin/env node
// Installs Devbook's mandatory rule packs into the native, always-loaded
// instruction locations of a project, and checks them for drift in CI.
//
//   node docs/devbook/bin/devbook-sync.mjs --profiles web        # write (core is always added)
//   node docs/devbook/bin/devbook-sync.mjs                       # re-sync using devbook.json
//   node docs/devbook/bin/devbook-sync.mjs --check               # CI: exit 1 on missing, edited or stale files
//
// Run from the project root, or pass --root <dir>. Requires Node 18+ and no packages.
import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEVBOOK_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const RULES_DIR = join(DEVBOOK_DIR, 'rules');
const CONFIG_FILE = 'devbook.json';
const MANDATORY_PROFILE = 'core';
const TARGETS = [
  { dir: '.github/instructions', file: (p) => `devbook-${p}.instructions.md`, copilot: true },
  { dir: '.claude/rules', file: (p) => `devbook-${p}.md`, copilot: false },
];
const MANAGED_FILE = /^devbook-[a-z0-9-]+(\.instructions)?\.md$/;

export function parseArgs(argv) {
  const args = { check: false, root: process.cwd(), profiles: undefined };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') args.check = true;
    else if (arg === '--root') args.root = resolve(argv[++i] ?? '');
    else if (arg === '--profiles') args.profiles = (argv[++i] ?? '').split(',').map((p) => p.trim()).filter(Boolean);
    else if (arg === '--help' || arg === '-h') args.help = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return args;
}

function parseFrontmatter(source) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(source);
  if (!match) throw new Error('Rule pack is missing frontmatter');
  const data = Object.fromEntries(
    match[1].split('\n').map((line) => {
      const at = line.indexOf(':');
      return [line.slice(0, at).trim(), line.slice(at + 1).trim()];
    }),
  );
  return { data, body: source.slice(match[0].length).trimStart() };
}

export function loadPacks(rulesDir = RULES_DIR) {
  return new Map(
    readdirSync(rulesDir)
      .filter((f) => f.endsWith('.md'))
      .sort()
      .map((f) => {
        const { data, body } = parseFrontmatter(readFileSync(join(rulesDir, f), 'utf8'));
        return [f.replace(/\.md$/, ''), { ...data, body }];
      }),
  );
}

export function devbookVersion(devbookDir = DEVBOOK_DIR) {
  return JSON.parse(readFileSync(join(devbookDir, 'package.json'), 'utf8')).version;
}

export function resolveProfiles(requested, available) {
  const profiles = [MANDATORY_PROFILE, ...requested.filter((p) => p !== MANDATORY_PROFILE)];
  const unknown = profiles.filter((p) => !available.has(p));
  if (unknown.length) {
    throw new Error(`Unknown profile(s): ${unknown.join(', ')}. Available: ${[...available.keys()].join(', ')}`);
  }
  return [...new Set(profiles)];
}

export function renderFile({ profile, pack, copilot, devbookPath, version }) {
  const header = `<!-- Generated by Devbook v${version} from ${devbookPath}/rules/${profile}.md. Do not edit. Re-run: node ${devbookPath}/bin/devbook-sync.mjs -->`;
  const body = pack.body.replaceAll('{{devbook}}', devbookPath);
  // applyTo "**" makes Copilot attach the pack to every request that touches a file.
  const frontmatter = copilot
    ? `---\napplyTo: "**"\ndescription: "${pack.description.replaceAll('"', "'")}"\n---\n\n`
    : '';
  return `${frontmatter}${header}\n\n${body}`.replace(/\n*$/, '\n');
}

export function expectedFiles({ root, profiles, packs, devbookDir = DEVBOOK_DIR }) {
  const devbookPath = relative(root, devbookDir).split(sep).join('/') || '.';
  const version = devbookVersion(devbookDir);
  const files = new Map();
  for (const target of TARGETS) {
    for (const profile of profiles) {
      files.set(
        `${target.dir}/${target.file(profile)}`,
        renderFile({ profile, pack: packs.get(profile), copilot: target.copilot, devbookPath, version }),
      );
    }
  }
  return files;
}

function managedFilesOnDisk(root) {
  return TARGETS.flatMap((target) => {
    const dir = join(root, target.dir);
    if (!existsSync(dir)) return [];
    return readdirSync(dir).filter((f) => MANAGED_FILE.test(f)).map((f) => `${target.dir}/${f}`);
  });
}

function readConfig(root) {
  const path = join(root, CONFIG_FILE);
  if (!existsSync(path)) return undefined;
  const config = JSON.parse(readFileSync(path, 'utf8'));
  if (!Array.isArray(config.profiles)) throw new Error(`${CONFIG_FILE} must contain a "profiles" array`);
  return config;
}

export function check({ root, profiles, packs, devbookDir = DEVBOOK_DIR }) {
  const problems = [];
  const expected = expectedFiles({ root, profiles, packs, devbookDir });
  for (const [path, content] of expected) {
    const full = join(root, path);
    if (!existsSync(full)) problems.push(`missing: ${path}`);
    else if (readFileSync(full, 'utf8') !== content) problems.push(`edited or stale: ${path}`);
  }
  for (const path of managedFilesOnDisk(root)) {
    if (!expected.has(path)) problems.push(`not in ${CONFIG_FILE} profiles: ${path}`);
  }
  return problems;
}

export function sync({ root, profiles, packs, devbookDir = DEVBOOK_DIR }) {
  const expected = expectedFiles({ root, profiles, packs, devbookDir });
  for (const path of managedFilesOnDisk(root)) {
    if (!expected.has(path)) rmSync(join(root, path));
  }
  for (const [path, content] of expected) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  writeFileSync(join(root, CONFIG_FILE), `${JSON.stringify({ profiles }, null, 2)}\n`);
  return [...expected.keys()];
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const packs = loadPacks();
  if (args.help) {
    console.log(`Usage: devbook-sync.mjs [--profiles ${[...packs.keys()].join(',')}] [--check] [--root <dir>]`);
    return 0;
  }
  if (args.check && args.profiles) throw new Error(`--check reads profiles from ${CONFIG_FILE}; do not pass --profiles`);
  const config = readConfig(args.root);
  if (args.check && !config) {
    console.error(`devbook: ${CONFIG_FILE} not found in ${args.root}. Run the sync without --check first.`);
    return 1;
  }
  const profiles = resolveProfiles(args.profiles ?? config?.profiles ?? [], packs);

  if (args.check) {
    const problems = check({ root: args.root, profiles, packs });
    if (problems.length) {
      console.error(`devbook: baseline rules are out of sync (${problems.length} problem(s)):`);
      for (const p of problems) console.error(`  - ${p}`);
      console.error('Fix: re-run devbook-sync.mjs without --check and commit the result. Do not edit generated files.');
      return 1;
    }
    console.log(`devbook: baseline rules OK (v${devbookVersion()}; profiles: ${profiles.join(', ')})`);
    return 0;
  }

  const written = sync({ root: args.root, profiles, packs });
  console.log(`devbook: wrote v${devbookVersion()} rules for ${profiles.join(', ')}:`);
  for (const path of [...written, CONFIG_FILE]) console.log(`  ${path}`);
  return 0;
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (error) {
    console.error(`devbook: ${error.message}`);
    process.exitCode = 1;
  }
}
