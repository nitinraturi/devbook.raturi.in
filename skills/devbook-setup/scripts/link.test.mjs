// link.mjs and verify.mjs against a scratch project that has this repository's files in .devbook/.
import { execFileSync, spawnSync } from 'node:child_process';
import {
	cpSync,
	existsSync,
	lstatSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	symlinkSync,
	writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { link } from './link.mjs';
import { plan } from './lib.mjs';
import { verify } from './verify.mjs';

const repo = new URL('../../../', import.meta.url).pathname;
const dirs = [];
after(() => dirs.forEach((d) => rmSync(d, { recursive: true, force: true })));

const AGENTS = `# AGENTS.md

## Project
- What: a test site.

## Devbook
@.devbook/instructions/core.md
@.devbook/instructions/security.md
@.devbook/instructions/testing.md

- \`.devbook/instructions/design.md\`: UI
- \`.devbook/instructions/seo.md\`: pages
- \`.devbook/stacks/<stack>.md\`: work that touches <stack>
- \`.devbook/skills/devbook-upgrade/SKILL.md\`: when asked
`;

function project({ agents = AGENTS } = {}) {
	const dir = mkdtempSync(join(tmpdir(), 'devbook-link-'));
	dirs.push(dir);
	execFileSync('git', ['init', '-q'], { cwd: dir });
	for (const p of ['instructions', 'stacks', 'skills', 'templates', 'devbook.manifest.json'])
		cpSync(join(repo, p), join(dir, '.devbook', p), { recursive: true });
	writeFileSync(join(dir, 'AGENTS.md'), agents);
	writeFileSync(join(dir, 'CLAUDE.md'), '@AGENTS.md\n');
	mkdirSync(join(dir, '.github'));
	writeFileSync(join(dir, '.github/copilot-instructions.md'), 'Follow AGENTS.md.\n');
	return dir;
}

test('plan links the chosen path rules for Claude and Copilot, and the matching skills', () => {
	const dests = plan(project()).map((e) => e.dest);
	assert.ok(dests.includes('.claude/rules/devbook-design.md'));
	assert.ok(dests.includes('.github/instructions/devbook-seo.instructions.md'));
	assert.ok(dests.includes('.claude/skills/devbook-seo-audit'), 'seo brings its skill');
	assert.ok(dests.includes('.claude/skills/devbook-security-review'), 'always-linked skill');
	assert.ok(!dests.includes('.claude/skills/devbook-db-migration'), 'database was not chosen');
	assert.ok(!dests.some((d) => d.includes('devbook-setup')), 'setup is never linked');
	assert.ok(!dests.some((d) => d.includes('devbook-core')), 'always-tier files are imported, not linked');
});

test('link creates symlinks that verify accepts, and a second run changes nothing', () => {
	const dir = project();
	assert.ok(verify(dir).some((p) => p.includes('is missing')));
	const first = link(dir);
	assert.equal(first.mode, 'link');
	assert.ok(lstatSync(join(dir, '.claude/rules/devbook-design.md')).isSymbolicLink());
	assert.match(readFileSync(join(dir, '.claude/rules/devbook-design.md'), 'utf8'), /DES-01/);
	assert.deepEqual(verify(dir), []);
	assert.ok(link(dir).actions.every((a) => a.action === 'ok'));
});

test('--dry-run writes nothing', () => {
	const dir = project();
	const { actions } = link(dir, { dryRun: true });
	assert.ok(actions.some((a) => a.action.startsWith('created')));
	assert.ok(!existsSync(join(dir, '.claude')));
});

test('copy mode writes generated copies, verify catches drift, and a rerun refreshes them', () => {
	const dir = project();
	link(dir, { copy: true });
	const rule = join(dir, '.claude/rules/devbook-design.md');
	assert.ok(!lstatSync(rule).isSymbolicLink());
	const text = readFileSync(rule, 'utf8');
	assert.match(text, /^---\n[\s\S]*?\n---\n<!-- Generated by Devbook from \.devbook\/instructions\/design\.md/);
	assert.match(readFileSync(join(dir, '.claude/skills/devbook-upgrade/SKILL.md'), 'utf8'), /Generated by Devbook/);
	writeFileSync(rule, `${text}\n- stale edit\n`);
	assert.ok(verify(dir).some((p) => p.includes('devbook-design.md is out of date')));
	link(dir, { copy: true });
	assert.equal(readFileSync(rule, 'utf8'), text);
});

test('leaves files it did not make alone and reports stale links', () => {
	const dir = project();
	mkdirSync(join(dir, '.claude/rules'), { recursive: true });
	writeFileSync(join(dir, '.claude/rules/devbook-design.md'), 'our own rules\n');
	const { actions } = link(dir);
	assert.match(actions.find((a) => a.dest === '.claude/rules/devbook-design.md').action, /^skipped/);
	assert.equal(readFileSync(join(dir, '.claude/rules/devbook-design.md'), 'utf8'), 'our own rules\n');

	writeFileSync(join(dir, 'AGENTS.md'), AGENTS.replace(/^- `\.devbook\/instructions\/seo\.md`.*\n/m, ''));
	assert.ok(!verify(dir).some((p) => p.includes('devbook-seo.md')), 'an extra link that resolves is fine');
	assert.match(link(dir).actions.find((a) => a.dest === '.claude/rules/devbook-seo.md').action, /^stale/);
	rmSync(join(dir, '.devbook/instructions/content.md'));
	symlinkSync('../../.devbook/instructions/content.md', join(dir, '.claude/rules/devbook-content.md'));
	assert.ok(verify(dir).some((p) => p.includes('devbook-content.md is broken')));
	link(dir, { prune: true });
	assert.ok(!existsSync(join(dir, '.claude/rules/devbook-seo.md')));
});

test('verify reports missing paths and a CLAUDE.md without the import', () => {
	const dir = project({ agents: `${AGENTS}- \`.devbook/instructions/nope.md\`: never\n` });
	writeFileSync(join(dir, 'CLAUDE.md'), 'Read AGENTS.md.\n');
	link(dir);
	const problems = verify(dir);
	assert.ok(problems.some((p) => p.includes('.devbook/instructions/nope.md, which does not exist')));
	assert.ok(problems.some((p) => p.includes('CLAUDE.md')));
});

test('the CLI explains a missing manifest', () => {
	const dir = project();
	rmSync(join(dir, '.devbook/devbook.manifest.json'));
	const result = spawnSync('node', [new URL('link.mjs', import.meta.url).pathname, '--root', dir], {
		encoding: 'utf8',
	});
	assert.equal(result.status, 2);
	assert.match(result.stderr, /devbook\.manifest\.json is missing/);
});

test('cursor gets generated .mdc rules: always tier always applies, path tier by glob', () => {
	const dir = project();
	link(dir, { assistants: ['claude', 'copilot', 'cursor'] });
	const core = readFileSync(join(dir, '.cursor/rules/devbook-core.mdc'), 'utf8');
	assert.match(
		core,
		/^---\ndescription: ".+"\nalwaysApply: true\n---\n<!-- Generated by Devbook from \.devbook\/instructions\/core\.md/,
	);
	assert.match(core, /CORE-02/);
	assert.doesNotMatch(core, /^title:/m, 'the source frontmatter is replaced');
	const design = readFileSync(join(dir, '.cursor/rules/devbook-design.mdc'), 'utf8');
	assert.match(design, /^globs: \*\*\/\*\.css,/m);
	assert.match(design, /^alwaysApply: false$/m);
	assert.ok(!existsSync(join(dir, '.cursor/rules/devbook-database.mdc')), 'database was not chosen');
	assert.deepEqual(verify(dir, { assistants: ['claude', 'copilot', 'cursor'] }), []);
	// A stale generated rule is caught and refreshed.
	writeFileSync(join(dir, '.cursor/rules/devbook-core.mdc'), `${core}extra\n`);
	assert.ok(verify(dir, { assistants: ['cursor'] }).some((p) => p.includes('devbook-core.mdc is out of date')));
	link(dir, { assistants: ['claude', 'copilot', 'cursor'] });
	assert.equal(readFileSync(join(dir, '.cursor/rules/devbook-core.mdc'), 'utf8'), core);
});

test('codex gets skill links in .agents/skills; copilot-review gets copies and an always-on instruction', () => {
	const dir = project();
	link(dir, { assistants: ['claude', 'copilot', 'codex', 'copilot-review'] });
	assert.ok(lstatSync(join(dir, '.agents/skills/devbook-upgrade')).isSymbolicLink());
	const design = join(dir, '.github/instructions/devbook-design.instructions.md');
	assert.ok(!lstatSync(design).isSymbolicLink(), 'copies, so github.com can read them');
	assert.match(readFileSync(design, 'utf8'), /^---\n[\s\S]*applyTo:/);
	const core = readFileSync(join(dir, '.github/instructions/devbook-core.instructions.md'), 'utf8');
	assert.match(core, /^---\napplyTo: "\*\*"\n---\n<!-- Generated by Devbook/);
	assert.deepEqual(verify(dir, { assistants: ['claude', 'copilot', 'codex', 'copilot-review'] }), []);
});

test('an unknown assistant is an error', () => {
	assert.throws(() => plan(project(), { assistants: ['gemini'] }), /unknown assistant/);
});
