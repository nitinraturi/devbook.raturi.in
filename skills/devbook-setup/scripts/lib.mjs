// Shared by link.mjs and verify.mjs: what Devbook writes into a project for each assistant, worked out from
// .devbook/devbook.manifest.json (each file's tier and adapters) and the files the project's AGENTS.md lists.
// Node only, no dependencies.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** The marker that makes a copied file Devbook's to refresh. A file without it is the project's and is left alone. */
export const GENERATED = 'Generated by Devbook';
export const header = (source) =>
	`<!-- ${GENERATED} from ${source}. Don't edit: change the source and rerun .devbook/skills/devbook-setup/scripts/link.mjs. -->\n`;

const FRONTMATTER = /^---\n([\s\S]*?)\n---\n/;

/** Insert the generated-file header after the frontmatter, so tools still read the frontmatter first. */
export function withHeader(text, source) {
	const fm = text.match(FRONTMATTER);
	return fm ? `${fm[0]}${header(source)}${text.slice(fm[0].length)}` : `${header(source)}${text}`;
}

/** The `description:` of a Markdown file's frontmatter (one line, optionally quoted). */
export function description(text) {
	const line =
		text
			.match(FRONTMATTER)?.[1]
			.match(/^description:\s*(.+)$/m)?.[1]
			?.trim() ?? '';
	return line.replace(/^(['"])(.*)\1$/, '$2');
}

const body = (text) => text.replace(FRONTMATTER, '');

/**
 * The text of a generated file. `copy` keeps the source as is; `mdc` writes a Cursor rule (always-tier files
 * always apply, path-tier files attach by glob, the rest are agent-requested by description); `copilot-all` writes a
 * Copilot instruction that applies to every file, for Copilot code review, which reads instruction files but not `@`
 * imports.
 */
export function render(text, { source, render: kind, tier, globs }) {
	if (kind === 'mdc') {
		const lines = [`description: ${JSON.stringify(description(text))}`];
		if (tier === 'path') lines.push(`globs: ${globs.join(',')}`);
		lines.push(`alwaysApply: ${tier === 'always'}`);
		return `---\n${lines.join('\n')}\n---\n${header(source)}${body(text)}`;
	}
	if (kind === 'copilot-all') return `---\napplyTo: "**"\n---\n${header(source)}${body(text)}`;
	return withHeader(text, source);
}

export function loadManifest(root) {
	const file = join(root, '.devbook', 'devbook.manifest.json');
	if (!existsSync(file)) {
		throw new Error(
			`${file} is missing. Update .devbook/ (the submodule includes it; for a copy, rerun the copy command from .devbook/templates/setup-prompt.md).`,
		);
	}
	return JSON.parse(readFileSync(file, 'utf8'));
}

/** `.devbook/...` paths that AGENTS.md lists, as `@` imports or "read when" lines. */
export function listedPaths(agents) {
	const out = [];
	for (const [, path] of agents.matchAll(/(?:^@|^- `)\.devbook\/([^\s`]+)/gm)) if (!path.includes('<')) out.push(path);
	return out;
}

/**
 * Assistants link.mjs can write for. Claude Code and Copilot (VS Code, CLI and cloud agent) by default. `cursor`
 * adds generated .cursor/rules/*.mdc files; `codex` adds .agents/skills links; `copilot-review` makes Copilot's
 * instruction files plain copies (github.com may not follow symlinks) and adds the always-loaded rules for every file.
 */
export const ASSISTANTS = ['claude', 'copilot', 'cursor', 'codex', 'copilot-review'];
export const DEFAULT_ASSISTANTS = ['claude', 'copilot'];

/**
 * Every file Devbook writes in the project: { dest, source, kind, render, tier, globs }. `source` and `dest` are
 * relative to the project root; `kind` is 'file' or 'dir'; `render` is 'link' (a symlink, or a copy where links
 * fail), 'copy', 'mdc' or 'copilot-all'.
 */
export function plan(root, { assistants = DEFAULT_ASSISTANTS } = {}) {
	const unknown = assistants.filter((a) => !ASSISTANTS.includes(a));
	if (unknown.length) throw new Error(`unknown assistant(s): ${unknown.join(', ')}; use ${ASSISTANTS.join(', ')}`);
	const manifest = loadManifest(root);
	const agentsFile = join(root, 'AGENTS.md');
	if (!existsSync(agentsFile))
		throw new Error('AGENTS.md is missing. Write it from .devbook/templates/AGENTS.md first.');
	const chosen = new Set(listedPaths(readFileSync(agentsFile, 'utf8')));
	const review = assistants.includes('copilot-review');
	const out = new Map();
	for (const f of manifest.files) {
		const picked =
			f.kind === 'skill'
				? f.linkWith === 'always' || chosen.has(f.linkWith)
				: f.tier === 'always' || chosen.has(f.path);
		if (!picked) continue;
		const name = f.kind === 'skill' ? f.path.split('/')[1] : f.path.split('/').pop().replace(/\.md$/, '');
		for (const id of f.adapters ?? []) {
			const adapter = manifest.adapters[id];
			if (!adapter.assistants.some((a) => assistants.includes(a))) continue;
			// With copilot-review, Copilot's files are copies, so code review on github.com can read them.
			const kind = id === 'copilot-instructions' && review ? 'copy' : adapter.render;
			const dest = adapter.dest.replace('{name}', name);
			const source = f.kind === 'skill' ? `.devbook/skills/${name}` : `.devbook/${f.path}`;
			out.set(dest, {
				dest,
				source,
				kind: f.kind === 'skill' ? 'dir' : 'file',
				render: kind,
				tier: f.tier,
				globs: f.globs,
			});
		}
	}
	return [...out.values()];
}

/** Folders link.mjs manages; `devbook-*` entries in them that the plan doesn't list are stale. */
export const MANAGED_DIRS = [
	'.claude/rules',
	'.github/instructions',
	'.claude/skills',
	'.cursor/rules',
	'.agents/skills',
];
