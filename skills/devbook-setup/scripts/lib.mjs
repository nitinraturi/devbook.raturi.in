// Shared by link.mjs and verify.mjs: what Devbook links into a project, worked out from .devbook/devbook.manifest.json
// and the files the project's AGENTS.md lists. Node only, no dependencies.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** The marker that makes a copied file Devbook's to refresh. A file without it is the project's and is left alone. */
export const GENERATED = 'Generated by Devbook';
export const header = (source) =>
	`<!-- ${GENERATED} from ${source}. Don't edit: change the source and rerun .devbook/skills/devbook-setup/scripts/link.mjs. -->\n`;

/** Insert the generated-file header after the frontmatter, so tools still read the frontmatter first. */
export function withHeader(text, source) {
	const fm = text.match(/^---\n[\s\S]*?\n---\n/);
	return fm ? `${fm[0]}${header(source)}${text.slice(fm[0].length)}` : `${header(source)}${text}`;
}

export function loadManifest(root) {
	const file = join(root, '.devbook', 'devbook.manifest.json');
	if (!existsSync(file)) {
		throw new Error(
			`${file} is missing. Update .devbook/ (the submodule includes it; for a copy, rerun the copy command from .devbook/templates/setup-prompt.md).`,
		);
	}
	return JSON.parse(readFileSync(file, 'utf8'));
}

/** `.devbook/...` paths that AGENTS.md lists, as `@` imports or "read when" lines. */
export function listedPaths(agents) {
	const out = [];
	for (const [, path] of agents.matchAll(/(?:^@|^- `)\.devbook\/([^\s`]+)/gm)) if (!path.includes('<')) out.push(path);
	return out;
}

/** Assistants to write files for. Claude Code and Copilot by default; more come from --assistants. */
export const DEFAULT_ASSISTANTS = ['claude', 'copilot'];

/**
 * Every link Devbook makes in the project: { dest, source, kind, assistant }. `source` is relative to the
 * project root, `dest` too; `kind` is 'file' or 'dir'.
 */
export function plan(root, { assistants = DEFAULT_ASSISTANTS } = {}) {
	const manifest = loadManifest(root);
	const agentsFile = join(root, 'AGENTS.md');
	if (!existsSync(agentsFile))
		throw new Error('AGENTS.md is missing. Write it from .devbook/templates/AGENTS.md first.');
	const chosen = new Set(listedPaths(readFileSync(agentsFile, 'utf8')));
	const out = [];
	for (const f of manifest.files) {
		if (f.kind !== 'instruction' || f.tier !== 'path' || !chosen.has(f.path)) continue;
		const name = f.path.split('/').pop().replace(/\.md$/, '');
		const source = `.devbook/${f.path}`;
		if (assistants.includes('claude'))
			out.push({ dest: `.claude/rules/devbook-${name}.md`, source, kind: 'file', assistant: 'claude' });
		if (assistants.includes('copilot'))
			out.push({
				dest: `.github/instructions/devbook-${name}.instructions.md`,
				source,
				kind: 'file',
				assistant: 'copilot',
			});
	}
	for (const f of manifest.files) {
		if (f.kind !== 'skill' || f.linked === false) continue;
		if (f.linkWith !== 'always' && !chosen.has(f.linkWith)) continue;
		const skill = f.path.split('/')[1];
		if (assistants.includes('claude') || assistants.includes('copilot'))
			out.push({
				dest: `.claude/skills/${skill}`,
				source: `.devbook/skills/${skill}`,
				kind: 'dir',
				assistant: 'claude',
			});
	}
	return out;
}

/** Folders link.mjs manages; `devbook-*` entries in them that the plan doesn't list are stale. */
export const MANAGED_DIRS = ['.claude/rules', '.github/instructions', '.claude/skills'];
